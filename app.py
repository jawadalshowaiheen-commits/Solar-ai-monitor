import streamlit as st

st.set_page_config(page_title='Solar AI Monitor', page_icon='☀️', layout='wide')
st.title('☀️ Solar AI Monitor')
st.subheader('Smart Solar Panel Performance Monitoring')
st.write('An interactive prototype to explore factors that may affect solar panel performance.')

st.sidebar.header('Environmental conditions')
temperature = st.sidebar.slider('Panel temperature (°C)', 10, 90, 40)
dust = st.sidebar.slider('Dust accumulation (%)', 0, 100, 20)
humidity = st.sidebar.slider('Humidity (%)', 0, 100, 40)

estimated_loss = min(95, max(0, (temperature - 25) * 0.35 + dust * 0.25 + humidity * 0.05))
col1, col2, col3 = st.columns(3)
col1.metric('Temperature', f'{temperature} °C')
col2.metric('Illustrative estimated loss', f'{estimated_loss:.1f}%')
col3.metric('Risk level', 'High' if estimated_loss >= 25 else 'Moderate' if estimated_loss >= 12 else 'Low')

st.subheader('Suggested actions')
if dust >= 50:
    st.warning('Consider inspecting panel cleanliness and cleaning when appropriate.')
if temperature >= 60:
    st.warning('Check ventilation and the panel manufacturer operating limits.')
if estimated_loss < 12:
    st.success('The selected conditions indicate a low estimated risk in this prototype.')
else:
    st.info('Compare actual energy output with expected production and inspect the system if needed.')

st.caption('Prototype only: estimates are illustrative, not generated by a trained AI model. Validated forecasting requires real historical panel, weather, and production data.')
